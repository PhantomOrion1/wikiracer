// Builds the language versions of the game from index.html + tools/i18n/strings.js:
//   lang/<code>/i18n.js   the dictionary i18n.js uses to translate the game live
//   <code>/index.html     the home page, pre-translated (so search engines read it in that language)
// Run after editing index.html or the translations:  node tools/build-langs.js
// (lang/<code>/data.js, the translated article pool, comes from tools/build-lang-data.js.)
const fs = require('fs');
const path = require('path');
const S = require('./i18n/strings');

const ROOT = path.join(__dirname, '..');
const LANGS = [['es', 'es', 1], ['pt', 'pt-BR', 2], ['de', 'de', 3], ['fr', 'fr', 4]]; // [folder, html lang, column]
const SITE = 'https://wikiracer.live';

const decode = (s) => s.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>');
const encText = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const encAttr = (s) => encText(s).replace(/"/g, '&quot;');

const src = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const version = (src.match(/app\.js\?v=(\d+)/) || [])[1] || '1';

for (const [code, htmlLang, col] of LANGS) {
  const meta = S.meta[code];
  const exact = S.exact.filter((r) => r[col]).map((r) => [r[0], r[col]]);
  const dict = {
    lang: code,
    exact,
    patterns: S.patterns.map((r) => [r[0], r[col]]),
    scoped: S.scoped.map((r) => [r[0], r[1], r[col + 1]]),
    demo: S.demo[code],
  };
  const dir = path.join(ROOT, 'lang', code);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'i18n.js'), `// Generated by tools/build-langs.js from tools/i18n/strings.js. Do not edit by hand.\nwindow.I18N_DICT = ${JSON.stringify(dict)};\n`);

  // ---- the pre-translated page ----
  const map = new Map(exact);
  const tr = (raw) => {
    const m = decode(raw).match(/^(\s*)([\s\S]*?)(\s*)$/);
    const core = m[2].replace(/\s+/g, ' ');
    return map.has(core) ? m[1] + map.get(core) + m[3] : null;
  };
  let html = src;
  // Words that mean different things in different places ("left" under the timer = time left).
  for (const [sel, en, out] of dict.scoped) {
    if (!sel.startsWith('#')) continue;
    const id = sel.slice(1);
    html = html.replace(new RegExp(`(id="${id}"[\\s\\S]*?)>${en}<`), `$1>${encText(out)}<`);
  }
  const [head, rest] = [html.slice(0, html.indexOf('<body')), html.slice(html.indexOf('<body'))];
  // Body text and attributes (not inside scripts, the demo board or the language switcher).
  let body = rest.replace(/(<script[\s\S]*?<\/script>)|(<nav class="lang-switch"[\s\S]*?<\/nav>)|>([^<]+)</g, (all, script, nav, text) => {
    if (script || nav) return all;
    const out = tr(text);
    return out == null ? all : `>${encText(out)}<`;
  });
  body = body.replace(/\b(placeholder|title|aria-label)="([^"]*)"/g, (all, a, v) => {
    const out = tr(v);
    return out == null ? all : `${a}="${encAttr(out)}"`;
  });
  body = body.replace(/(<nav class="lang-switch"[\s\S]*?<\/nav>)/, (nav) => nav
    .replace(/ aria-current="page"/g, '')
    .replace(`href="/${code}/"`, `href="/${code}/" aria-current="page"`));
  // Article pool for this language instead of the English one, plus the live translator.
  body = body
    .replace(/\s*<script src="\/pairs\.js[^"]*" defer><\/script>/, '')
    .replace(/<script src="\/vital\.js[^"]*" defer><\/script>/, `<script src="/lang/${code}/data.js?v=${version}" defer></script>`)
    .replace(/<script src="\/app\.js/, `<script src="/lang/${code}/i18n.js?v=${version}" defer></script>\n  <script src="/i18n.js?v=${version}" defer></script>\n  <script src="/app.js`);

  let h = head
    .replace('<html lang="en">', `<html lang="${htmlLang}">`)
    .replace(/<title>[^<]*<\/title>/, `<title>${encText(meta.title)}</title>`)
    .replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${encAttr(meta.description)}">`)
    .replace(/<meta property="og:title" content="[^"]*">/, `<meta property="og:title" content="${encAttr(meta.title)}">`)
    .replace(/<meta property="og:description" content="[^"]*">/, `<meta property="og:description" content="${encAttr(meta.description)}">`)
    .replace(/<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${SITE}/${code}/">`)
    .replace(/<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${SITE}/${code}/">`)
    .replace(/<script type="application\/ld\+json">(\{[^<]*"VideoGame"[^<]*\})<\/script>/, (all, json) => {
      const j = JSON.parse(json);
      Object.assign(j, { url: `${SITE}/${code}/`, description: meta.description, inLanguage: htmlLang });
      return `<script type="application/ld+json">${JSON.stringify(j)}</script>`;
    })
    .replace(/<script type="application\/ld\+json">(\{[^<]*"WebSite"[^<]*\})<\/script>/, (all, json) => {
      const j = JSON.parse(json);
      Object.assign(j, { url: `${SITE}/${code}/`, inLanguage: htmlLang });
      return `<script type="application/ld+json">${JSON.stringify(j)}</script>`;
    });
  html = h + body;
  fs.mkdirSync(path.join(ROOT, code), { recursive: true });
  fs.writeFileSync(path.join(ROOT, code, 'index.html'), html);
  const left = [...body.replace(/<script[\s\S]*?<\/script>/g, '').matchAll(/>([^<]*[A-Za-z][^<]*)</g)].map((m) => decode(m[1]).trim()).filter((t) => t && !map.has(t) && ![...map.values()].includes(t));
  console.log(`${code}: ${exact.length} phrases, ${S.patterns.length} patterns · untranslated text left in page: ${[...new Set(left)].join(' | ') || 'none'}`);
}
