// Builds the article pool and curated pairs for each non-English language from the English ones,
// using Wikipedia's own interlanguage links (so every title is a real article on that Wikipedia).
// Writes lang/<code>/data.js, which language pages load instead of vital.js + pairs.js.
//   node tools/build-lang-data.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..');
const LANGS = ['es', 'pt', 'de', 'fr'];
const UA = 'WikiRacerLangBuilder/1.0 (https://wikiracer.live)';

const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'vital.js'), 'utf8'), ctx);
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'pairs.js'), 'utf8'), ctx);
const { POOL, PAIRS } = ctx.window;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function api(params) {
  const url = `https://en.wikipedia.org/w/api.php?${new URLSearchParams({ format: 'json', formatversion: '2', maxlag: '5', ...params })}`;
  for (let i = 0; i < 5; i++) {
    const r = await fetch(url, { headers: { 'User-Agent': UA } });
    if (r.ok) { const j = await r.json(); if (!j.error) { await sleep(100); return j; } }
    await sleep(1500 * (i + 1));
  }
  throw new Error('API failed');
}

// English title → { es: '…', pt: '…', … } (follows English redirects first).
async function translations(titles) {
  const out = {};
  for (let i = 0; i < titles.length; i += 50) {
    const batch = titles.slice(i, i + 50);
    let cont = {};
    const pages = {};
    const from = {};
    do {
      const j = await api({ action: 'query', titles: batch.join('|'), redirects: '1', prop: 'langlinks', lllimit: 'max', ...cont });
      for (const n of j.query.normalized || []) from[n.to] = n.from;
      for (const r of j.query.redirects || []) from[r.to] = from[r.from] || r.from;
      for (const p of j.query.pages) {
        pages[p.title] = pages[p.title] || {};
        for (const l of p.langlinks || []) if (LANGS.includes(l.lang)) pages[p.title][l.lang] = l.title;
      }
      cont = j.continue || null;
    } while (cont);
    for (const [t, links] of Object.entries(pages)) {
      out[t] = links;
      if (from[t]) out[from[t]] = links;
    }
  }
  return out;
}

(async () => {
  const titles = new Set(POOL.familiar.map(([t]) => t));
  for (const list of Object.values(PAIRS)) for (const [a, b] of list) { titles.add(a); titles.add(b); }
  const tr = await translations([...titles]);
  for (const lang of LANGS) {
    const T = (t) => (tr[t] && tr[t][lang]) || null;
    const seen = new Set();
    const familiar = [];
    for (const [t, g] of POOL.familiar) { const x = T(t); if (x && !seen.has(x)) { seen.add(x); familiar.push([x, g]); } }
    const pairs = {};
    for (const [k, list] of Object.entries(PAIRS)) pairs[k] = list.map(([a, b]) => [T(a), T(b)]).filter(([a, b]) => a && b && a !== b);
    const data = { familiar, subjects: POOL.subjects, ranked: [] };
    const file = path.join(ROOT, 'lang', lang, 'data.js');
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, `// Generated by tools/build-lang-data.js from vital.js + pairs.js via Wikipedia interlanguage links.\nwindow.POOL = ${JSON.stringify(data)};\nwindow.PAIRS = ${JSON.stringify(pairs)};\n`);
    console.log(`${lang}: ${familiar.length}/${POOL.familiar.length} topics, pairs ${Object.entries(pairs).map(([k, v]) => `${k} ${v.length}/${PAIRS[k].length}`).join(', ')}`);
  }
})();
